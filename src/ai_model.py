"""AI design assistant — physics-informed surrogate of the sourced RC engine.

The model is a set of gradient-boosted regression trees trained OFFLINE
(scripts/ml/train_model.py) on a dataset generated by the validated RC
engine itself (scripts/ml/generate_dataset.py, real hourly weather for
12 Indian cities across all climate zones). Inference here is pure NumPy
(a compact JSON tree export, no scikit-learn at runtime) so the serverless
bundle stays small and the deployed physics never drifts.

Honesty contract (project rule: no invented numbers):
  * The AI only ever predicts metrics that were computed by the engine.
  * Accuracy (MAE / R2, incl. leave-one-site-out) is exported with the
    model and served by GET /api/ai/info — the UI always shows it.
  * The engine remains the source of truth: predictions are labelled
    estimates, and every suggestion can be engine-verified.
"""

from __future__ import annotations

import json
import math
import os
from pathlib import Path

import numpy as np
import pandas as pd

MODEL_FILE = Path(__file__).resolve().parent / "data" / "ai_model.json"

# --------------------------------------------------------------------------
# feature schema (ORDER MATTERS — must match the exported model)
# --------------------------------------------------------------------------
SITE_FEATURES = [
    "t_hottest_month_c", "t_coldest_month_c", "diurnal_range_c",
    "rh_mean_pct", "cdd18", "hdd18", "ghi_mean_w_m2", "wind_mean_ms",
    # v2: outdoor extremes + altitude. The targets are extremes, so a model
    # given only monthly means had to memorise each site to predict them and
    # could not transfer to an unseen one.
    "t_min_c", "t_max_c", "elevation_m",
]
DESIGN_FEATURES = [
    "length_m", "width_m", "height_m",
    "wall_r", "wall_mass_kg_m2", "wall_abs",
    "roof_r", "roof_mass_kg_m2", "roof_abs",
    "ins_r", "win_area_m2", "win_u_w_m2k", "win_shgc",
    "orient_sin", "orient_cos",
]
FEATURES = SITE_FEATURES + DESIGN_FEATURES

# Hot-week AND cold-week targets. v1 predicted only cold_min_c for winter,
# which says nothing about whether a cold-climate shelter is actually liveable
# — Leh, Dras, Kargil and Srinagar are designed against the cold week.
TARGETS = ["hot_mean_c", "hot_max_c", "hot_comfort_fraction",
           "cold_min_c", "cold_mean_c", "cold_comfort_fraction"]

#: Physics-informed residual targets (v2).
#:
#: Indoor extremes track the OUTDOOR extreme plus an envelope-dependent
#: offset. Fitting the absolute value made the trees span a 44.9 C range
#: across sites, and gradient-boosted trees cannot extrapolate: a site colder
#: than anything in training got clamped to the nearest leaf, which is why
#: leave-one-site-out MAE for cold_min_c was 11.5 C on Srinagar even though
#: the random holdout scored R2 = 1.0000.
#:
#: Fitting `indoor - outdoor` instead collapses that 44.9 C span to 2.5-13.4 C,
#: and an unseen site's offset lands INSIDE the range other sites already
#: cover — interpolation rather than extrapolation. The baseline is a feature
#: the model already receives, so inference just adds it back.
RESIDUAL_BASE = {
    "cold_min_c": "t_min_c",
    "cold_mean_c": "t_min_c",
    "hot_max_c": "t_max_c",
    "hot_mean_c": "t_max_c",
}

